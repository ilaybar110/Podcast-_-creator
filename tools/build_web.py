"""Sync the voice direction from app/prompts.py into the browser app (docs/js/prompts_data.js).

The GitHub Pages version runs entirely in the browser, so it can't import Python. This keeps
one source of truth for the director's notes: run it after editing app/prompts.py.
    python -m tools.build_web
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import budget, prompts  # noqa: E402

OUT = ROOT / "docs" / "js" / "prompts_data.js"


def render() -> str:
    data = {
        "STYLES": prompts.STYLES, "PACES": prompts.PACES, "ACCENT": prompts.ACCENT,
        "DELIVERY": prompts.DELIVERY, "RULES": prompts.RULES,
        "FREE_DEFAULTS": budget.DEFAULT_LIMITS, "FREE_CHUNK_CHARS": budget.FREE_CHUNK_CHARS,
    }
    body = json.dumps(data, ensure_ascii=False, indent=1)
    return ("// GENERATED by tools/build_web.py from app/prompts.py and app/budget.py - do not edit.\n"
            f"export const DATA = {body};\n")


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")
